// Generates src/output/ymd_patterns.rs (VE-3728):
//
//   env -i PATH="$PATH" LANG=C node scripts/gen-ymd-patterns.mjs > src/output/ymd_patterns.rs
//
// `toLocaleDateString()` formats with the CLDR `yMd` skeleton (ECMA-402 numeric year, month and
// day). ICU4X 2.3 has no runtime skeleton matching: its short date pattern zero-pads where `yMd`
// doesn't (de `dd.MM.y` vs `d.M.y`). This records Node's pattern for every locale its ICU has
// data for, rebuilt from `formatToParts`. Only Gregorian-calendar locales are listed; the Rust CLI
// formats the others (th, fa, ar-SA, …) with ICU4X's calendar-aware formatter.
import { nodeLocaleTags, rustString as rust } from './node-locales.mjs';

/** ICU pattern letters must be quoted in literal text. */
const quote = (text) => text.replace(/'/g, "''").replace(/[A-Za-z]+/g, (letters) => `'${letters}'`);

function ymdPattern(tag) {
  // `und` given explicitly resolves to the default locale, so root data needs the default
  // locale to be root itself; `LANG=` (set but empty) does that, and gives `y-MM-dd`.
  if (tag === 'und') return 'y-MM-dd';
  const format = new Intl.DateTimeFormat(tag, { timeZone: 'UTC' });
  if (format.resolvedOptions().calendar !== 'gregory') return null;
  const single = format.formatToParts(Date.UTC(2026, 0, 5, 12));
  const double = format.formatToParts(Date.UTC(2026, 10, 23, 12));
  if (single.map((p) => p.type).join() !== double.map((p) => p.type).join()) throw new Error(`${tag}: parts differ`);
  return single
    .map((part) => {
      const width = [...part.value].length;
      switch (part.type) {
        case 'year':
          return 'y';
        case 'month':
          return width === 2 ? 'MM' : 'M';
        case 'day':
          return width === 2 ? 'dd' : 'd';
        case 'literal':
          return quote(part.value);
        default:
          throw new Error(`${tag}: unexpected ${part.type} part`);
      }
    })
    .join('');
}

const rows = [];
const skipped = [];
for (const tag of nodeLocaleTags()) {
  try {
    const pattern = ymdPattern(tag);
    if (pattern === null) skipped.push(tag);
    else rows.push([tag, pattern]);
  } catch (err) {
    skipped.push(`${tag} (${err.message})`);
  }
}
const patterns = [...new Set(rows.map(([, pattern]) => pattern))].sort();

console.log(`//! Generated by \`scripts/gen-ymd-patterns.mjs\` from Node ${process.version} (ICU ${process.versions.icu},
//! CLDR ${process.versions.cldr}). Do not edit; regenerate. ${rows.length} locales, ${patterns.length} patterns.
//! Not listed (non-Gregorian default calendar): ${skipped.join(', ')}.

/// The distinct \`yMd\` patterns.
pub(super) static PATTERNS: [&str; ${patterns.length}] = [
${patterns.map((p) => `    ${rust(p)},`).join('\n')}
];

/// Locale tag → index into [\`PATTERNS\`], sorted by tag.
pub(super) static LOCALES: [(&str, u8); ${rows.length}] = [
${rows.map(([tag, pattern]) => `    (${rust(tag)}, ${patterns.indexOf(pattern)}),`).join('\n')}
];`);
