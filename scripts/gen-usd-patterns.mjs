// Generates rust/src/output/usd_patterns.rs (VE-3728):
//
//   env -i PATH="$PATH" LANG=C node scripts/gen-usd-patterns.mjs > rust/src/output/usd_patterns.rs
//
// The measurement views print money with `n.toLocaleString(undefined, { style: 'currency',
// currency: 'USD', maximumFractionDigits: 2 })`. ICU4X 2.3 has no stable currency formatter, so
// this records, for every locale Node's ICU has data for, the text Node puts around the amount
// (symbol, sign, spacing, bidi marks) and the separators currency amounts use where they differ
// from plain numbers. The Rust CLI formats the amount itself with ICU4X's decimal formatter.
import { execFileSync } from 'node:child_process';

import { nodeLocaleTags, rustString as rust } from './node-locales.mjs';

const OPTIONS = { style: 'currency', currency: 'USD', maximumFractionDigits: 2 };
const AMOUNT = new Set(['integer', 'group', 'decimal', 'fraction', 'infinity']);

/** `n` formatted for `tag` (undefined: the default locale), with the amount replaced by `{n}`. */
function shape(tag, n) {
  let text = '';
  let state = 'before';
  for (const part of new Intl.NumberFormat(tag, OPTIONS).formatToParts(n)) {
    if (AMOUNT.has(part.type)) {
      if (state === 'after') throw new Error(`${tag}: the amount is split in ${n}`);
      if (state === 'before') text += '{n}';
      state = 'in';
    } else {
      if (state === 'in') state = 'after';
      text += part.value;
    }
  }
  return text;
}

/** Positive, negative, +∞ and -∞ amounts. */
const shapes = (tag) => [shape(tag, 1234.5), shape(tag, -1234.5), shape(tag, Infinity), shape(tag, -Infinity)];

function separators(tag, options) {
  const parts = new Intl.NumberFormat(tag, options).formatToParts(1234567.5);
  return [parts.find((p) => p.type === 'group')?.value ?? '', parts.find((p) => p.type === 'decimal')?.value ?? ''];
}

if (process.argv[2] === 'default') {
  // `und` given explicitly resolves to the default locale, so root data needs the default locale
  // to be root itself: `LANG=` (set but empty) does that.
  console.log(JSON.stringify({ locale: Intl.NumberFormat().resolvedOptions().locale, shapes: shapes(undefined) }));
} else {
  const root = JSON.parse(
    execFileSync(process.execPath, [new URL(import.meta.url).pathname, 'default'], {
      env: { PATH: process.env.PATH, LANG: '' },
    }).toString(),
  );
  if (root.locale !== 'und') throw new Error(`LANG= resolved to ${root.locale}`);

  const rows = [];
  const symbols = [];
  for (const tag of nodeLocaleTags()) {
    rows.push([tag, JSON.stringify(tag === 'und' ? root.shapes : shapes(tag))]);
    if (tag === 'und') continue;
    const [group, decimal] = separators(tag, {});
    const [currencyGroup, currencyDecimal] = separators(tag, OPTIONS);
    if (group !== currencyGroup || decimal !== currencyDecimal) {
      symbols.push([tag, group, decimal, currencyGroup, currencyDecimal]);
    }
  }
  const distinct = [...new Set(rows.map(([, s]) => s))].sort();
  // One line per entry, or one line per string where that passes 120 columns, as rustfmt has it.
  const entry = (s) => {
    const strings = JSON.parse(s).map(rust);
    const line = `    (${strings.join(', ')}),`;
    return line.length <= 120 ? line : `    (\n${strings.map((x) => `        ${x},`).join('\n')}\n    ),`;
  };

  console.log(`//! Generated by \`scripts/gen-usd-patterns.mjs\` from Node ${process.version} (ICU ${process.versions.icu},
//! CLDR ${process.versions.cldr}). Do not edit; regenerate. ${rows.length} locales, ${distinct.length} shapes.

/// The text around the amount in \`n.toLocaleString(locale, { style: 'currency', currency: 'USD' })\`,
/// \`{n}\` standing for the amount: (positive, negative, +∞, -∞).
pub(super) type Shapes = (&'static str, &'static str, &'static str, &'static str);

/// (number group, number decimal, currency group, currency decimal) separators.
pub(super) type Separators = (&'static str, &'static str, &'static str, &'static str);

pub(super) static SHAPES: [Shapes; ${distinct.length}] = [
${distinct.map(entry).join('\n')}
];

/// Locale tag → index into [\`SHAPES\`], sorted by tag.
pub(super) static LOCALES: [(&str, u8); ${rows.length}] = [
${rows.map(([tag, s]) => `    (${rust(tag)}, ${distinct.indexOf(s)}),`).join('\n')}
];

/// Locales whose currency amounts use other separators than their plain numbers, sorted by tag.
pub(super) static SEPARATORS: [(&str, Separators); ${symbols.length}] = [
${symbols.map(([tag, ...s]) => `    (${rust(tag)}, (${s.map(rust).join(', ')})),`).join('\n')}
];`);
}
